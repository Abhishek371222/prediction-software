#!/usr/bin/env python3
"""Bake the UI assets (logos, tool icons, fonts) into EmbeddedAssets.cpp/h.

Why: the app used to load these from an Assets/ folder found by walking up from
the CWD or the EXE. That works in the dev tree, but a recipient who downloads
only the .exe has no such folder anywhere above it, so every logo, ribbon icon
and bundled typeface silently failed to load -- which looks exactly like an old
build with missing artwork. Embedding makes the EXE self-contained, the same way
Tools/embed_q21s_pack.py already does for the Q21S CSVs.

Re-run this whenever the files under ShyamGui/Assets change, then rebuild:

    python ShyamGui/Tools/embed_assets.py
"""
from __future__ import annotations

from pathlib import Path

ROOT   = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "Assets"
OUT_H   = ROOT / "Source" / "EmbeddedAssets.h"
OUT_CPP = ROOT / "Source" / "EmbeddedAssets.cpp"

# Keys are the lookup names the app asks for: a path relative to Assets/,
# always with forward slashes.
PATTERNS = [
    "Atomik_Logo_Light.png",
    "Atomik_Logo_Dark.png",
    "Fonts/Montserrat-Regular.ttf",
    "Fonts/Montserrat-Medium.ttf",
    "Fonts/Montserrat-SemiBold.ttf",
    "Fonts/Montserrat-Bold.ttf",
    "Fonts/SpaceMono-Regular.ttf",
    "Fonts/SpaceMono-Bold.ttf",
    # File cluster glyphs - the ribbon reads these five by name from
    # Assets/FigmaRedesign, not from ToolIcons.
    "FigmaRedesign/figma_icon_file_add_new.png",
    "FigmaRedesign/figma_icon_file_open_folder.png",
    "FigmaRedesign/figma_icon_file_save.png",
    "FigmaRedesign/figma_icon_file_save_as.png",
    "FigmaRedesign/figma_icon_file_export_pdf.png",
]
GLOBS = ["ToolIcons/*.png", "ToolIcons/*.svg"]


def c_ident(rel: str) -> str:
    return "k_" + "".join(ch if ch.isalnum() else "_" for ch in rel)


def byte_rows(blob: bytes, per_row: int = 20):
    for i in range(0, len(blob), per_row):
        yield ",".join(str(b) if b < 128 else str(b - 256) for b in blob[i:i + per_row])


def main() -> None:
    entries: list[tuple[str, Path]] = []

    for rel in PATTERNS:
        p = ASSETS / rel
        if p.is_file():
            entries.append((rel, p))
        else:
            print(f"  WARNING: missing {rel}")

    for pattern in GLOBS:
        for p in sorted(ASSETS.glob(pattern)):
            entries.append((p.relative_to(ASSETS).as_posix(), p))

    if not entries:
        raise SystemExit(f"No assets found under {ASSETS}")

    h = [
        "#pragma once",
        "// Auto-generated by Tools/embed_assets.py - do not edit by hand.",
        "// UI assets (logos, tool icons, fonts) baked in so the EXE runs with no",
        "// sidecar Assets/ folder. See BrandTheme.h, which prefers these over disk.",
        "",
        "namespace EmbeddedAssets",
        "{",
        "    struct Entry",
        "    {",
        "        const char* name;   // path relative to Assets/, forward slashes",
        "        const char* data;   // raw file bytes (not NUL-terminated)",
        "        int         size;",
        "    };",
        "",
        f"    static constexpr int numFiles = {len(entries)};",
        "    const Entry* getFiles() noexcept;",
        "    /** Exact match on the relative path, e.g. \"ToolIcons/Pencil.png\". */",
        "    const Entry* find (const char* name) noexcept;",
        "}",
        "",
    ]
    OUT_H.write_text("\n".join(h), encoding="utf-8")

    c = [
        '#include "EmbeddedAssets.h"',
        "// Auto-generated by Tools/embed_assets.py - do not edit by hand.",
        "",
        "#include <cstring>",
        "",
        "namespace EmbeddedAssets",
        "{",
        "namespace",
        "{",
    ]

    total = 0
    for rel, path in entries:
        blob = path.read_bytes()
        total += len(blob)
        c.append(f"    // {rel}  ({len(blob)} bytes)")
        c.append(f"    static const char {c_ident(rel)}[] = {{")
        for row in byte_rows(blob):
            c.append(f"        {row},")
        c.append("    };")
        c.append("")

    c.append("    static const Entry kEntries[] = {")
    for rel, path in entries:
        ident = c_ident(rel)
        c.append(f'        {{ "{rel}", {ident}, (int) sizeof ({ident}) }},')
    c.append("    };")
    c.append("}   // anonymous namespace")
    c.append("")
    c.append("const Entry* getFiles() noexcept { return kEntries; }")
    c.append("")
    c.append("const Entry* find (const char* name) noexcept")
    c.append("{")
    c.append("    if (name == nullptr) return nullptr;")
    c.append("    for (const auto& e : kEntries)")
    c.append("        if (std::strcmp (e.name, name) == 0)")
    c.append("            return &e;")
    c.append("    return nullptr;")
    c.append("}")
    c.append("}   // namespace EmbeddedAssets")
    c.append("")

    OUT_CPP.write_text("\n".join(c), encoding="utf-8")

    print(f"Embedded {len(entries)} files, {total/1024:.0f} KiB of data")
    print(f"  {OUT_H}")
    print(f"  {OUT_CPP}  ({OUT_CPP.stat().st_size/1048576:.1f} MB source)")


if __name__ == "__main__":
    main()
