#!/usr/bin/env python3
"""Bake BEM2inch MeasurementIntegrationPack CSVs into EmbeddedBEM2inchData.cpp/h.

Mirror of Tools/embed_q21s_pack.py, retargeted at the BEM2inch polar set so the
EXE can load BEM2inch readings without a sidecar Data/ folder, exactly like
Q21S. Re-run this script whenever the BEM2inch CSVs change, then rebuild.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "prediction software" / "MeasurementIntegrationPack" / "Data"
OUT_H = ROOT / "Source" / "EmbeddedBEM2inchData.h"
OUT_CPP = ROOT / "Source" / "EmbeddedBEM2inchData.cpp"


def c_ident(name: str) -> str:
    out = []
    for ch in name:
        if ch.isalnum():
            out.append(ch)
        else:
            out.append("_")
    return "k_" + "".join(out)


def main() -> None:
    files = sorted(PACK.glob("BEM2inch_*.csv"))
    if not files:
        raise SystemExit(f"No BEM2inch_*.csv under {PACK}")

    # Optional index used only for diagnostics / future tooling.
    manifest = PACK / "manifest.csv"
    entries: list[tuple[str, Path]] = [(f.name, f) for f in files]
    if manifest.exists():
        entries.append((manifest.name, manifest))

    h = []
    h.append("#pragma once")
    h.append("// Auto-generated by Tools/embed_bem2inch_pack.py — do not edit by hand.")
    h.append("// BEM2inch polar CSVs embedded so the EXE runs without a Data/ folder.")
    h.append("")
    h.append("namespace EmbeddedBEM2inch")
    h.append("{")
    h.append("    struct Entry")
    h.append("    {")
    h.append("        const char* fileName;   // e.g. BEM2inch_64Hz_2p0m.csv")
    h.append("        const char* data;       // raw file bytes (not NUL-terminated)")
    h.append("        int         size;")
    h.append("    };")
    h.append("")
    h.append(f"    static constexpr int numFiles = {len(entries)};")
    h.append("    const Entry* getFiles() noexcept;")
    h.append("    const Entry* find (const char* fileName) noexcept;")
    h.append("    bool hasFile (const char* fileName) noexcept;")
    h.append("}")
    h.append("")
    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")

    cpp = []
    cpp.append('#include "EmbeddedBEM2inchData.h"')
    cpp.append("#include <cstring>")
    cpp.append("// Auto-generated by Tools/embed_bem2inch_pack.py — do not edit by hand.")
    cpp.append("")
    cpp.append("namespace EmbeddedBEM2inch")
    cpp.append("{")
    cpp.append("namespace {")

    for name, path in entries:
        raw = path.read_bytes()
        ident = c_ident(name)
        cpp.append(f"static const char {ident}[] = {{")
        line = []
        for i, b in enumerate(raw):
            line.append(f"{b}")
            if len(line) >= 24:
                cpp.append("    " + ", ".join(line) + ",")
                line = []
        if line:
            cpp.append("    " + ", ".join(line))
        cpp.append("};")
        cpp.append(f"static constexpr int {ident}_size = {len(raw)};")
        cpp.append("")

    cpp.append("static const Entry kFiles[numFiles] = {")
    for name, path in entries:
        ident = c_ident(name)
        cpp.append(f'    {{ "{name}", {ident}, {ident}_size }},')
    cpp.append("};")
    cpp.append("} // namespace")
    cpp.append("")
    cpp.append("const Entry* getFiles() noexcept { return kFiles; }")
    cpp.append("")
    cpp.append("const Entry* find (const char* fileName) noexcept")
    cpp.append("{")
    cpp.append("    if (fileName == nullptr) return nullptr;")
    cpp.append("    for (int i = 0; i < numFiles; ++i)")
    cpp.append("        if (std::strcmp (kFiles[i].fileName, fileName) == 0)")
    cpp.append("            return &kFiles[i];")
    cpp.append("    return nullptr;")
    cpp.append("}")
    cpp.append("")
    cpp.append("bool hasFile (const char* fileName) noexcept")
    cpp.append("{")
    cpp.append("    return find (fileName) != nullptr;")
    cpp.append("}")
    cpp.append("} // namespace EmbeddedBEM2inch")
    cpp.append("")

    OUT_CPP.write_text("\n".join(cpp) + "\n", encoding="utf-8")
    total = sum(p.stat().st_size for _, p in entries)
    print(f"Wrote {OUT_H.name} + {OUT_CPP.name}: {len(entries)} files, {total} bytes")


if __name__ == "__main__":
    main()
